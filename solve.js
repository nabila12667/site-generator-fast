// A faster drop-in for makefun-site 1.0.0: run(input) returns exactly the answer
// makefun-site 1.0.0's build returns for the same input, byte for byte. Same rules
// (README.md of makefun-site 1.0.0; its code is the reference wherever the two
// differ), reimplemented leaner: no token arrays in the Markdown pass, no regex
// per character in the inline pass, an ASCII fast path for slugs, and no
// allocation where a slice or a counter does the job. No network, no clock, no
// cache from one case to the next: every per-case cache is reset in run().

// ---------------------------------------------------------------- text

/** The HTML escape table. */
const ESC = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

/** Fast HTML escape: native scans for the next special character, no allocation when none. */
function esc(s) {
  let out = '';
  let start = 0;
  const len = s.length;
  for (;;) {
    let j = len;
    let k = s.indexOf('&', start);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('<', start);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('>', start);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('"', start);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf("'", start);
    if (k !== -1 && k < j) j = k;
    if (j >= len) break;
    if (j > start) out += s.slice(start, j);
    out += ESC[s[j]];
    start = j + 1;
  }
  return start === 0 ? s : out + s.slice(start);
}

/** The same escape, pushed in pieces into `out` (an array of strings). */
function escInto(s, out) {
  let start = 0;
  const len = s.length;
  for (;;) {
    let j = len;
    let k = s.indexOf('&', start);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('<', start);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('>', start);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('"', start);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf("'", start);
    if (k !== -1 && k < j) j = k;
    if (j >= len) break;
    if (j > start) out.push(s.slice(start, j));
    out.push(ESC[s[j]]);
    start = j + 1;
  }
  if (start < len) out.push(s.slice(start));
}

/** Slugs of this case's texts (reset by run(): nothing is cached across cases). */
let SLUGS = new Map();

const SLUG_MAX = 64;

/** The slug of `text`, exactly as makefun-site's slugify. */
function slugify(text) {
  const hit = SLUGS.get(text);
  if (hit !== undefined) return hit;
  let ascii = true;
  for (let i = 0; i < text.length; i++) {
    if (text.charCodeAt(i) > 127) {
      ascii = false;
      break;
    }
  }
  let out;
  if (ascii) {
    // Pure ASCII: NFKD is the identity and there are no combining marks.
    out = '';
    let gap = false;
    for (let i = 0; i < text.length; i++) {
      const ch = text[i];
      let keep = null;
      if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
      else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
      if (keep === null) {
        gap = out.length > 0;
        continue;
      }
      if (gap) out += '-';
      gap = false;
      out += keep;
    }
    out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
    if (out === '') out = 'untitled';
  } else {
    const plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
    out = '';
    let gap = false;
    for (const ch of plain) {
      let keep = null;
      if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
      else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
      if (keep === null) {
        gap = out.length > 0;
        continue;
      }
      if (gap) out += '-';
      gap = false;
      out += keep;
    }
    out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
    if (out === '') out = 'untitled';
  }
  SLUGS.set(text, out);
  return out;
}

/** `slug` made unique against `taken` (and added to it). */
function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/** A YYYY-MM-DD date in words, from the string alone. */
function longDate(date) {
  const [y, m, d] = date.split('-');
  return `${Number(d)} ${MONTHS[Number(m) - 1]} ${y}`;
}

/** Whether code `c` is a JavaScript \s whitespace character. */
function isWSCode(c) {
  if (c > 32) {
    if (c < 127) return false;
    return (
      c === 160 || c === 0x1680 || (c >= 0x2000 && c <= 0x200a) || c === 0x2028 || c === 0x2029 ||
      c === 0x202f || c === 0x205f || c === 0x3000 || c === 0xfeff
    );
  }
  return c === 9 || c === 10 || c === 11 || c === 12 || c === 13 || c === 32;
}

/** Whether `s` holds any \s whitespace character. */
function hasWS(s) {
  for (let i = 0; i < s.length; i++) if (isWSCode(s.charCodeAt(i))) return true;
  return false;
}

/** The words of a body: its runs of characters other than whitespace. */
function wordsOf(text) {
  let n = 0;
  let inWord = false;
  for (let i = 0; i < text.length; i++) {
    const c = text.charCodeAt(i);
    const ws =
      c <= 32
        ? c === 9 || c === 10 || c === 11 || c === 12 || c === 13 || c === 32
        : c < 127
          ? false
          : c === 160 ||
            c === 0x1680 ||
            (c >= 0x2000 && c <= 0x200a) ||
            c === 0x2028 ||
            c === 0x2029 ||
            c === 0x202f ||
            c === 0x205f ||
            c === 0x3000 ||
            c === 0xfeff;
    if (ws) inWord = false;
    else if (!inWord) {
      inWord = true;
      n++;
    }
  }
  return n;
}

/** Whether `line` is blank (empty or only spaces and tabs). */
function isBlank(line) {
  if (line.length === 0) return true;
  const c0 = line.charCodeAt(0);
  if (c0 !== 32 && c0 !== 9) return false;
  for (let i = 1; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** `line` with spaces and tabs at either end dropped. */
function trimLine(line) {
  let s = 0;
  let e = line.length;
  while (s < e && (line.charCodeAt(s) === 32 || line.charCodeAt(s) === 9)) s++;
  while (e > s && (line.charCodeAt(e - 1) === 32 || line.charCodeAt(e - 1) === 9)) e--;
  return line.slice(s, e);
}

// ---------------------------------------------------------------- front matter

const KEYS = ['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary'];

function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31;
}

/** A string value: "..." with \" and \\ its only escapes, or bare. */
function stringOf(raw) {
  if (raw.startsWith('"')) {
    if (raw.length < 2 || !raw.endsWith('"')) return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1)
          return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw.startsWith('[')) return { error: 'a bare string opens on [' };
  return { value: raw };
}

/** Whether `raw` is a real day from 1970-01-01 to 2099-12-31 (YYYY-MM-DD). */
function dateOk(raw) {
  if (raw.length !== 10 || raw[4] !== '-' || raw[7] !== '-') return false;
  for (let i = 0; i < 10; i++) {
    if (i === 4 || i === 7) continue;
    const c = raw.charCodeAt(i);
    if (c < 48 || c > 57) return false;
  }
  const y = Number(raw.slice(0, 4));
  const mo = Number(raw.slice(5, 7));
  const d = Number(raw.slice(8, 10));
  return !(y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo));
}

/** One key's value, or why it is refused. */
function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date':
      return dateOk(raw)
        ? { value: raw }
        : { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
    case 'tags': {
      if (!raw.startsWith('[') || !raw.endsWith(']')) return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      for (const t of tags) {
        if (t === '' || t.indexOf('"') !== -1 || t.indexOf('[') !== -1 || t.indexOf(']') !== -1)
          return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
      }
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout': {
      if (raw.length === 0) return { error: 'key "layout": not a template name' };
      for (let i = 0; i < raw.length; i++) {
        const c = raw.charCodeAt(i);
        if (!((c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 45))
          return { error: 'key "layout": not a template name' };
      }
      return { value: raw };
    }
    case 'slug': {
      if (raw.length === 0 || raw.length > 64) return { error: 'key "slug": not a slug' };
      let prevDash = true;
      for (let i = 0; i < raw.length; i++) {
        const c = raw.charCodeAt(i);
        const alnum = (c >= 97 && c <= 122) || (c >= 48 && c <= 57);
        if (c === 45) {
          if (prevDash) return { error: 'key "slug": not a slug' };
          prevDash = true;
        } else if (alnum) prevDash = false;
        else return { error: 'key "slug": not a slug' };
      }
      if (prevDash) return { error: 'key "slug": not a slug' };
      return { value: raw };
    }
    default:
      return { error: `unknown key "${key}"` };
  }
}

/**
 * A source's front matter and body: { data, body }, or { error } with the first
 * reason it is refused. `text` has "\n" line ends.
 */
function parseFrontMatter(text) {
  const lines = text.split('\n');
  if (lines[0] !== '---') return { error: 'no front matter' };
  let close = -1;
  for (let i = 1; i < lines.length; i++) {
    if (lines[i] === '---') {
      close = i;
      break;
    }
  }
  if (close === -1) return { error: 'the front matter is not closed' };
  const data = {};
  for (let i = 1; i < close; i++) {
    const line = lines[i];
    if (isBlank(line) || line.charCodeAt(0) === 35) continue;
    const colon = line.indexOf(':');
    let key = null;
    let raw = null;
    if (colon > 0) {
      let ok = true;
      for (let k = 0; k < colon; k++) {
        const c = line.charCodeAt(k);
        if (!((c >= 97 && c <= 122) || c === 95)) {
          ok = false;
          break;
        }
      }
      if (ok) {
        key = line.slice(0, colon);
        if (colon === line.length - 1) raw = '';
        else if (line.charCodeAt(colon + 1) === 32) raw = line.slice(colon + 2);
      }
    }
    if (key === null) return { error: `line ${i + 1} is not "key: value"` };
    let e = raw.length;
    while (e > 0 && (raw.charCodeAt(e - 1) === 32 || raw.charCodeAt(e - 1) === 9)) e--;
    raw = raw.slice(0, e);
    if (!KEYS.includes(key)) return { error: `unknown key "${key}"` };
    if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
    if (raw === '') return { error: `key "${key}" has no value` };
    const v = valueOf(key, raw);
    if ('error' in v) return v;
    data[key] = v.value;
  }
  if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
  let bodyStart = 0;
  for (let k = 0; k <= close; k++) bodyStart += lines[k].length + 1;
  return { data, body: text.slice(bodyStart) };
}

// ---------------------------------------------------------------- markdown

/** The language of a fence-open line, or null when the line is not one. */
function fenceOpen(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return null;
  let j = 3;
  while (j < line.length) {
    const c = line.charCodeAt(j);
    if (!((c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45)) break;
    j++;
  }
  for (let k = j; k < line.length; k++) {
    const c = line.charCodeAt(k);
    if (c !== 32 && c !== 9) return null;
  }
  return line.slice(3, j);
}

/** Whether `line` closes a fence: three backticks, then spaces or tabs only. */
function isFenceClose(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return false;
  for (let k = 3; k < line.length; k++) {
    const c = line.charCodeAt(k);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** A heading line's level and text, or null (a heading's text is never empty). */
function headingOf(line) {
  let h = 0;
  while (h < line.length && line.charCodeAt(h) === 35) h++;
  if (h === 0 || h > 6 || h >= line.length) return null;
  const c = line.charCodeAt(h);
  if (c !== 32 && c !== 9) return null;
  let s = h;
  while (s < line.length && (line.charCodeAt(s) === 32 || line.charCodeAt(s) === 9)) s++;
  let e = line.length;
  while (e > s && (line.charCodeAt(e - 1) === 32 || line.charCodeAt(e - 1) === 9)) e--;
  if (e === s) return null;
  return { depth: h, text: line.slice(s, e) };
}

/** Whether `line` is a thematic break: `---` or `***`, then spaces or tabs only. */
function isHR(line) {
  const ok =
    (line.charCodeAt(0) === 45 && line.charCodeAt(1) === 45 && line.charCodeAt(2) === 45) ||
    (line.charCodeAt(0) === 42 && line.charCodeAt(1) === 42 && line.charCodeAt(2) === 42);
  if (!ok) return false;
  for (let k = 3; k < line.length; k++) {
    const c = line.charCodeAt(k);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** A bullet item's text, or null when the line is not `- ` or `* `. */
function bulletOf(line) {
  const c = line.charCodeAt(0);
  if ((c === 45 || c === 42) && line.charCodeAt(1) === 32) return line.slice(2);
  return null;
}

/** An ordered item's number and text, or null when the line is not `N. `. */
function orderedOf(line) {
  let j = 0;
  while (j < line.length && j < 9 && line.charCodeAt(j) >= 48 && line.charCodeAt(j) <= 57) j++;
  if (j === 0 || j >= line.length) return null;
  if (line.charCodeAt(j) !== 46 || line.charCodeAt(j + 1) !== 32) return null;
  return { num: line.slice(0, j), text: line.slice(j + 2) };
}

/** Whether `line` continues a list item: two or more spaces, then a non-space. */
function isContinued(line) {
  let j = 0;
  while (j < line.length && line.charCodeAt(j) === 32) j++;
  if (j < 2 || j >= line.length) return false;
  return !isWSCode(line.charCodeAt(j));
}

/** Whether `line` ends a paragraph: a blank line, a fence, a heading or a break. */
function endsParagraph(line) {
  if (line.length === 0) return true;
  const c = line.charCodeAt(0);
  if (c === 32 || c === 9) return isBlank(line);
  if (c === 96) return fenceOpen(line) !== null;
  if (c === 35) return headingOf(line) !== null;
  if (c === 45 || c === 42) return isHR(line);
  return false;
}

/** The characters a backslash escapes. */
const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);

/** The first index from `from` where `s` holds `what` outside a backslash escape, or -1. */
function findUnescaped(s, what, from) {
  for (let j = from; j <= s.length - what.length; j++) {
    if (s[j] === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

/** The first single * from `from` (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (c !== '*') continue;
    if (s[j + 1] === '*') {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

/**
 * `s` rendered inline into `out` (an array of strings); `env.link(target)` is a
 * link's href. Plain runs are escaped in bulk; only the construct characters
 * (`\`, backtick, `*`, `[`) break a run.
 */
function inlineInto(s, env, out) {
  let i = 0;
  let run = 0;
  const len = s.length;
  for (;;) {
    // The next construct character at or after i (native scan, no per-char loop).
    let j = len;
    let k = s.indexOf('\\', i);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('`', i);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('*', i);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('[', i);
    if (k !== -1 && k < j) j = k;
    if (j >= len) break;
    const c = s.charCodeAt(j);
    if (c === 92) {
      // backslash: before an escapable character it writes that character
      if (j + 1 < len && ESCAPABLE.has(s[j + 1])) {
        if (j > run) escInto(s.slice(run, j), out);
        const n = s[j + 1];
        out.push(n === '>' ? '&gt;' : n);
        i = j + 2;
        run = i;
      } else i = j + 1;
      continue;
    }
    if (c === 96) {
      // backtick: a code span closed by the next backtick, at least one char between
      const m = s.indexOf('`', j + 1);
      if (m > j + 1) {
        if (j > run) escInto(s.slice(run, j), out);
        out.push('<code>');
        escInto(s.slice(j + 1, m), out);
        out.push('</code>');
        i = m + 1;
        run = i;
      } else i = j + 1;
      continue;
    }
    if (c === 42) {
      // asterisk: strong, emphasis, or itself
      if (s.charCodeAt(j + 1) === 42) {
        const m = findUnescaped(s, '**', j + 2);
        if (m > j + 2) {
          if (j > run) escInto(s.slice(run, j), out);
          out.push('<strong>');
          inlineInto(s.slice(j + 2, m), env, out);
          out.push('</strong>');
          i = m + 2;
          run = i;
        } else i = j + 2;
        continue;
      }
      const m = findSingleStar(s, j + 1);
      if (m > j + 1) {
        if (j > run) escInto(s.slice(run, j), out);
        out.push('<em>');
        inlineInto(s.slice(j + 1, m), env, out);
        out.push('</em>');
        i = m + 1;
        run = i;
      } else i = j + 1;
      continue;
    }
    // '[': a link, or itself
    const q = findUnescaped(s, ']', j + 1);
    const m = q !== -1 && s.charCodeAt(q + 1) === 40 ? s.indexOf(')', q + 2) : -1;
    const target = m === -1 ? '' : s.slice(q + 2, m);
    if (target !== '' && !hasWS(target)) {
      if (j > run) escInto(s.slice(run, j), out);
      out.push('<a href="');
      escInto(env.link(target), out);
      out.push('">');
      inlineInto(s.slice(j + 1, q), env, out);
      out.push('</a>');
      i = m + 1;
      run = i;
    } else i = j + 1;
  }
  if (len > run) escInto(s.slice(run, len), out);
}

/**
 * `src` rendered: its HTML (each block on its own lines, a "\n" after the last),
 * its table of contents (every level 2 and 3 heading) and its excerpt (the first
 * paragraph's inline HTML, or ""). Lexing and rendering run in one pass.
 */
function renderMarkdown(src, env) {
  const lines = src.split('\n');
  const n = lines.length;
  const ids = new Set();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  let i = 0;
  while (i < n) {
    const line = lines[i];
    if (isBlank(line)) {
      i++;
      continue;
    }
    const lang = fenceOpen(line);
    if (lang !== null) {
      const body = [];
      i++;
      while (i < n && !isFenceClose(lines[i])) body.push(lines[i++]);
      i++;
      const cls = lang === '' ? '' : ` class="language-${esc(lang)}"`;
      let code = '';
      for (const l of body) code += esc(l) + '\n';
      blocks.push(`<pre><code${cls}>${code}</code></pre>\n`);
      continue;
    }
    const hd = headingOf(line);
    if (hd !== null) {
      const id = uniqueSlug(slugify(hd.text), ids);
      const out = [];
      inlineInto(hd.text, env, out);
      const html = out.join('');
      blocks.push(`<h${hd.depth} id="${id}">${html}</h${hd.depth}>\n`);
      if (hd.depth === 2 || hd.depth === 3) toc.push({ level: hd.depth, id, html });
      i++;
      continue;
    }
    if (isHR(line)) {
      blocks.push('<hr>\n');
      i++;
      continue;
    }
    if (line.charCodeAt(0) === 62) {
      const body = [];
      while (i < n && lines[i].charCodeAt(0) === 62) {
        const l = lines[i++];
        body.push(l.charCodeAt(1) === 32 ? l.slice(2) : l.slice(1));
      }
      const kept = [];
      for (const l of body) {
        const t = trimLine(l);
        if (t !== '') kept.push(t);
      }
      if (kept.length === 0) blocks.push('<blockquote>\n</blockquote>\n');
      else {
        const out = [];
        inlineInto(kept.join('\n'), env, out);
        blocks.push(`<blockquote>\n<p>${out.join('')}</p>\n</blockquote>\n`);
      }
      continue;
    }
    const bText = bulletOf(line);
    const oMatch = bText === null ? orderedOf(line) : null;
    if (bText !== null || oMatch !== null) {
      const isOrdered = oMatch !== null;
      const items = [];
      while (i < n) {
        const l = lines[i];
        if (isOrdered) {
          const m = orderedOf(l);
          if (m !== null) {
            items.push([trimLine(m.text)]);
            i++;
            continue;
          }
        } else {
          const m = bulletOf(l);
          if (m !== null) {
            items.push([trimLine(m)]);
            i++;
            continue;
          }
        }
        if (isContinued(l)) {
          items[items.length - 1].push(trimLine(l));
          i++;
          continue;
        }
        break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      const start = isOrdered ? Number(oMatch.num) : 1;
      const open = isOrdered && start !== 1 ? `<ol start="${start}">` : `<${tag}>`;
      let lis = '';
      for (const item of items) {
        const out = [];
        inlineInto(item.join('\n'), env, out);
        lis += `<li>${out.join('')}</li>\n`;
      }
      blocks.push(`${open}\n${lis}</${tag}>\n`);
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < n && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const out = [];
    inlineInto(body.join('\n'), env, out);
    const html = out.join('');
    if (excerpt === null) excerpt = html;
    blocks.push(`<p>${html}</p>\n`);
  }
  return { html: blocks.join(''), toc, excerpt: excerpt ?? '' };
}

